def pages():
    return sorted(
        p
        for p in DOCS.rglob("*.md")
        if not set(p.relative_to(DOCS).parts)
        & {
            "node_modules", ".vitepress", ".cli-ref", ".git", ".playwright-auth",
            ".playwright-cli", ".export-audit", "tests",
        }
        and str(p.relative_to(DOCS)) not in DRAFTS
        and not any(fnmatchcase(p.relative_to(DOCS).as_posix(), pattern) for pattern in PRIVATE_PAGES)
    )


def normalize(path):
    return re.sub(r"\{[^}]+\}", "{}", path.split("?")[0].rstrip("/"))


def source_routes():
    routes = []
    for path in sorted((ROOT / "pepplatform").rglob("*.py")):
        source = path.read_text()
        if not re.search(r"@(?:app|router)\.", source):
            continue
        tree = ast.parse(source)
        values = {}
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                try:
                    value = static_value(node.value, values)
                except (ValueError, KeyError, TypeError, IndexError):
                    continue
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        values[target.id] = value
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for deco in node.decorator_list:
                if not (
                    isinstance(deco, ast.Call)
                    and isinstance(deco.func, ast.Attribute)
                    and deco.func.attr.upper() in METHODS.split("|")
                    and deco.args
                ):
                    continue
                try:
                    route = static_value(deco.args[0], values)
                except (ValueError, KeyError, TypeError, IndexError):
                    raise ValueError(f"Unresolved route in {path}:{node.lineno}")
                if isinstance(route, str) and route.startswith("/api/"):
                    routes.append(
                        (deco.func.attr.upper(), route, str(path.relative_to(ROOT)), node.lineno)
                    )
    return sorted(routes)


def topic(path):
    if "/visualizations/" in path:
        return "visualizations"
    if path.startswith("/api/versions/") or path.endswith("/versions"):
        return "versions"
    if path.startswith("/api/inference-runs/") or "/predict" in path:
        return "inference"
    first = path.split("/")[2]
    return (
        first
        if first
        in {"auth", "ai", "admin", "agent", "datasets", "models", "ensembles", "experiments"}
        else "system"
    )


def write_indexes(routes):
    for name, language in LOCALES.items():
        zh = name == "zh"
        title = "API 路由索引" if zh else "API Route Index"
        intro = (
            "由后端注册路由生成，包含额外注册的版本及可视化接口。权限、字段与流式事件见对应主题页；此索引不替代接口说明。"
            if zh
            else "Generated from backend route registrations, including version and visualization modules. Follow each topic for permissions, fields and stream events; this index is not a schema reference."
        )
        lines = [
            f"# {title}",
            "",
            intro,
            "",
            "<!-- Generated by scripts/check_docs.py --write-api-index -->",
            "",
            f"> {len(routes)} API routes",
            "",
            "| Method | Path | Reference |",
            "| --- | --- | --- |",
        ]
        for method, path, _source, _line in routes:
            guide = topic(path)
            lines.append(f"| {method} | `{path}` | [{guide}](./{guide}) |")
        (DOCS / language / "api/routes.md").write_text("\n".join(lines) + "\n")


@lru_cache(None)
def arguments(script):
    path = ROOT / script
    return extract_add_argument_calls(ast.parse(path.read_text()), source_constants(path))


def known_flags(script):
    flags = set()
    for entry in arguments(script):
        flags.update([entry["name"], *entry.get("aliases", [])])
        if "BooleanOptionalAction" in entry["type"]:
            flags.add("--no-" + entry["name"].removeprefix("--"))
    return flags | {"--help", "-h"}


def check_argument_table(text, script, label, errors):
    """Compare the published cells, not just the extractor, with source facts."""
    if "<!-- BEGIN GENERATED CLI -->" not in text:
        return
    block = text.split("<!-- BEGIN GENERATED CLI -->", 1)[1].split(
        "<!-- END GENERATED CLI -->", 1
    )[0]
    rows = {}
    for line in block.splitlines():
        cells = [unescape(cell.strip()) for cell in line.strip().strip("|").split("|")]
        if len(cells) != 5:
            continue
        names = re.findall(r"`([^`]+)`", cells[0])
        if names:
            if names[0] in rows:
                errors.append(f"{label}: duplicate argument {names[0]}")
            rows[names[0]] = cells
    expected = {entry["name"]: entry for entry in arguments(script)}
    for name in sorted(rows.keys() ^ expected.keys()):
        errors.append(f"{label}: argument table/source differ for {name}")
    for name in rows.keys() & expected.keys():
        cells, entry = rows[name], expected[name]
        defaults = re.findall(r"`(.*?)`", cells[2])
        if entry["default"] == "'==SUPPRESS=='":
            valid_default = cells[2] in {"Unset (attribute omitted)", "未设置（不创建属性）"}
        else:
            valid_default = defaults == [entry["default"]]
        if not valid_default:
            errors.append(f"{label}: stale default for {name}")
        if cells[1] != (entry["type"] or "—"):
            errors.append(f"{label}: stale type for {name}")
        if re.findall(r"`(.*?)`", cells[0]) != [name, *entry.get("aliases", [])]:
            errors.append(f"{label}: stale aliases for {name}")
        # Task rows describe usable tasks, restricted after argparse parsing.
        # The formatter intentionally supplies this guidance when choices=None.
        if name != "--task_type":
            choices = [str(value) for value in entry.get("choices") or []]
            if entry.get("choices_expression") and not choices:
                choices = [entry["choices_expression"]]
            if re.findall(r"`(.*?)`", cells[3]) != choices:
                errors.append(f"{label}: stale choices for {name}")


def check_example_choices(script, tokens, label, errors):
    scripts = [script]
    if script == "scripts/train_pipeline.py":
        scripts.extend(("scripts/train_sequence_pipeline.py", "scripts/train_pair_pipeline.py"))
    options = {}
    for path in scripts:
        for entry in arguments(path):
            for name in [entry["name"], *entry.get("aliases", [])]:
                options[name] = entry
    for index, token in enumerate(tokens):
        name, separator, value = token.partition("=")
        entry = options.get(name)
        if entry is None or not entry.get("choices"):
            continue
        if not separator:
            if index + 1 == len(tokens) or tokens[index + 1].startswith("--"):
                continue
            value = tokens[index + 1]
        # Shell substitutions/placeholders cannot be resolved statically.
        if any(char in value for char in "$<>`"):
            continue
        if entry["type"] == "normalize_pair_strategy":
            # argparse runs the declared converter before testing choices.
            aliases = source_constants(ROOT / "pepplatform/pair_terminology.py")[
                "PAIR_STRATEGY_ALIASES"
            ]
            value = aliases.get(value.strip().lower(), value)
        if value not in {str(choice) for choice in entry["choices"]}:
            errors.append(f"{label}: invalid {script} choice {name}={value}")


def check_source_links(path, text, errors):
    for link in re.findall(r"(?<!!)\[[^\]\n]+\]\(([^)\n]+)\)", text):
        link = link.strip().split(' "')[0]
        parsed = urlsplit(link)
        if parsed.scheme or parsed.netloc or not parsed.path:
            continue
        target = (
            DOCS / unquote(parsed.path).lstrip("/")
            if parsed.path.startswith("/")
            else path.parent / unquote(parsed.path)
        )
        candidates = [target, target.with_suffix(".md"), target / "index.md"]
        if not any(p.is_file() for p in candidates):
            errors.append(f"{path.relative_to(DOCS)}: broken link {link}")


def check_internal_versions(text, label, errors):
    """Keep internal release numbers out of public prose and JSON examples."""
    # External URLs, DOIs and dependency requirements identify public resources.
    text = re.sub(r"https?://[^\s<>`]+|\b10\.\d{4,9}/[^\s<>`]+", "", text)
    # Alembic revision IDs remain exact, including beside rendered headings.
    text = re.sub(r"(?<!\d)20\d{6}_\d{4}(?!\d)", "", text)
    text = re.sub(
        r"\b(?:Python|Node(?:\.js)?|npm|VitePress|tsx|PyTorch|torch|scikit-learn|esm|BLAST\+)"
        r"\s*(?:(?:version|版本)\s*)?v?\d+(?:\.\d+)*",
        "",
        text,
        flags=re.I,
    )
    pattern = (
        r"(?<![\w/.-])v\d+(?:\.\d+)*\b"
        r"|\b(?:contract|schema|protocol|BoW|TF-IDF|Top-n-gram|DT|DR)[\s_`-]+v\d+(?!\d)"
        r"|\brole-boundary-sequence-join-v\d+\b"
        r"|\bversion\s+(?:is\s+)?\d+\b"
        r"|(?:协议|契约|格式|版本)[\s`_-]*(?:为|是)?\s*v?\d+(?:\.\d+)*|第\s*\d+\s*版"
        r"|[\"'][\w]*version[\"']\s*:\s*\d+(?:\.\d+)*"
    )
    for number, line in enumerate(text.splitlines(), 1):
        for match in re.finditer(pattern, line, re.I):
            errors.append(f"{label}:{number}: internal version identifier: {match[0]}")


def check_content(routes, errors):
    api = {}
    route_pattern = (
        rf"(?:^\#{{2,6}}\s+|^\|\s*`?)({METHODS})`?\s*(?:\|\s*`?|\s+)"
        r"(/api/[A-Za-z0-9_{}/?.=&:-]+)"
    )
    for language in LOCALES.values():
        # The generated route index must not disguise missing topic documentation.
        text = "\n".join(
            p.read_text() for p in (DOCS / language / "api").glob("*.md") if p.name != "routes.md"
        )
        documented = set()
        for match in re.finditer(route_pattern, text, re.M):
            documented.add((match[1], normalize(match[2])))
        api[language] = documented
        index_text = (DOCS / language / "api/routes.md").read_text()
        indexed = {
            (match[1], normalize(match[2]))
            for match in re.finditer(route_pattern, index_text, re.M)
        }
        errors.extend(
            f"{language}api: route index and topic coverage differ: {method} {path}"
            for method, path in sorted(indexed ^ documented)
        )
        if routes is not None:
            actual = {(m, normalize(p)) for m, p, _, _ in routes}
            errors.extend(
                f"{language}api: undocumented {method} {path}"
                for method, path in sorted(actual - documented)
            )
            errors.extend(
                f"{language}api: nonexistent documented route {method} {path}"
                for method, path in sorted(documented - actual)
            )
    if len({frozenset(value) for value in api.values()}) != 1:
        errors.append("Bilingual API topic coverage differs")
    paths = pages()
    nested = next(prefix.rstrip("/") for prefix in LOCALES.values() if prefix)
    translated = {}
    for name, prefix in LOCALES.items():
        translated[name] = {
            str(p.relative_to(DOCS / prefix))
            for p in paths
            if (p.relative_to(DOCS).parts[0] == nested) == bool(prefix)
        }
    zh, en = translated["zh"], translated["en"]
    errors.extend("Missing English page: " + p for p in sorted(zh - en))
    errors.extend("Missing Chinese page: " + p for p in sorted(en - zh))
    for path in paths:
        text = path.read_text()
        if str(path.relative_to(DOCS)) in DRAFTS:
            continue
        check_internal_versions(text, path.relative_to(DOCS), errors)
        for reference in re.findall(r"`((?:scripts|tools)/[\w-]+\.py)`", text):
            if reference not in PUBLIC_ENTRYPOINTS:
                errors.append(f"{path.relative_to(DOCS)}: unpublished platform script {reference}")
        if ROOT:
            for reference in re.findall(
                r"`((?:pepplatform|frontend|alembic|docker|docs)/[\w./-]+\.(?:py|ts|vue|md|toml|json))`",
                text,
            ):
                if not (ROOT / reference).is_file():
                    errors.append(f"{path.relative_to(DOCS)}: missing source reference {reference}")
        containers = []
        fenced = False
        for number, line in enumerate(text.splitlines(), 1):
            if line.startswith("```"):
                fenced = not fenced
            elif not fenced and line.startswith("::: "):
                containers.append(number)
            elif not fenced and line.strip() == ":::":
                if containers:
                    containers.pop()
                else:
                    errors.append(f"{path.relative_to(DOCS)}:{number}: unmatched callout end")
        if containers:
            errors.append(f"{path.relative_to(DOCS)}: unclosed callout at lines {containers}")
        if re.search(r"<ScreenshotFrame\b|<img\b|!\[[^\]]*\]\(", text):
            errors.append(f"{path.relative_to(DOCS)}: image reference in text-only documentation")
        if re.search(r"/(?:disk\d|home)/|\bcampus\b|校园|PEP_DOCS_DIR", text, re.I):
            errors.append(f"{path.relative_to(DOCS)}: obsolete local deployment reference")
        for address in re.findall(r"\b(?:\d{1,3}\.){3}\d{1,3}\b", text):
            try:
                ip = ipaddress.ip_address(address)
            except ValueError:
                continue
            if ip.is_private and not (ip.is_loopback or ip.is_unspecified):
                errors.append(f"{path.relative_to(DOCS)}: private network address")
        for block in re.finditer(r"^```json\s*\n(.*?)^```", text, re.M | re.S):
            try:
                json.loads(block[1])
            except ValueError as exc:
                errors.append(f"{path.relative_to(DOCS)}: invalid JSON: {exc}")
        for block in re.finditer(r"^```(?:bash|sh|json)\s*\n(.*?)^```", text, re.M | re.S):
            if not block[1].strip():
                errors.append(f"{path.relative_to(DOCS)}: empty executable/example code block")
        for block in (
            re.finditer(r"^```(?:bash|sh)\s*\n(.*?)^```", text, re.M | re.S) if ROOT else ()
        ):
            for line in block[1].replace("\\\n", " ").splitlines():
                match = re.search(
                    r"\bpython(?:3(?:\.10)?)?\s+((?:scripts|tools)/[\w-]+\.py)\b(.*)", line
                )
                if not match:
                    continue
                script = match[1]
                if not (ROOT / script).is_file():
                    errors.append(f"{path.relative_to(DOCS)}: missing script {script}")
                    continue
                try:
                    tokens = shlex.split(match[2], comments=True)
                except ValueError:
                    continue  # shell snippets may continue with quoted payloads
                flags = known_flags(script)
                if script == "scripts/train_pipeline.py":
                    # The compatibility dispatcher forwards unparsed options.
                    flags |= known_flags("scripts/train_sequence_pipeline.py") | known_flags(
                        "scripts/train_pair_pipeline.py"
                    )
                for flag in (t.split("=")[0] for t in tokens if t.startswith("--")):
                    if flag not in flags:
                        errors.append(f"{path.relative_to(DOCS)}: unknown {script} flag {flag}")
                check_example_choices(script, tokens, path.relative_to(DOCS), errors)
        check_source_links(path, re.sub(r"^```.*?^```", "", text, flags=re.M | re.S), errors)
    for script, name in [
        ("train_pipeline.py", "train-pipeline"),
        ("train_sequence_pipeline.py", "train-sequence-pipeline"),
        ("train_pair_pipeline.py", "train-pair-pipeline"),
    ]:
        for language in LOCALES.values():
            text = (DOCS / language / "cli" / (name + ".md")).read_text()
            if (
                text.count("<!-- BEGIN GENERATED CLI -->") != 1
                or text.count("<!-- END GENERATED CLI -->") != 1
            ):
                errors.append(f"{language}cli/{name}: missing generation markers")
            for entry in arguments("scripts/" + script) if ROOT else ():
                if f"`{entry['name']}`" not in text:
                    errors.append(f"{language}cli/{name}: missing {entry['name']}")
            if ROOT:
                check_argument_table(text, "scripts/" + script, f"{language}cli/{name}", errors)
    if ROOT:
        for prefix in LOCALES.values():
            text = (DOCS / prefix / "cli/tools.md").read_text()
            for folder, names in (("tools", PUBLIC_TOOLS), ("scripts", SUPPORTING_SCRIPTS)):
                for name in names:
                    heading = "### " + Path(name).stem + "\n"
                    if heading not in text:
                        errors.append(f"{prefix}cli/tools: missing {name}")
                        continue
                    block = text.split(heading, 1)[1]
                    block = re.split(r"^#{1,3} ", block, maxsplit=1, flags=re.M)[0]
                    block = block.split("<!-- END GENERATED CLI -->", 1)[0]
                    check_argument_table(
                        "<!-- BEGIN GENERATED CLI -->\n" + block + "<!-- END GENERATED CLI -->",
                        f"{folder}/{name}",
                        f"{prefix}cli/tools/{name}",
                        errors,
                    )
    print(f"Checked {len(paths)} Markdown pages and bilingual API/CLI references.")


def check_configuration(errors):
    names = set()
    for path in [*(ROOT / "pepplatform").rglob("*.py"), *(ROOT / "scripts").glob("*.py")]:
        names.update(re.findall(r"""["']((?:PEP_|PEPPLATFORM_)[A-Z0-9_]+)["']""", path.read_text()))
    revisions = set()
    for path in (ROOT / "alembic/versions").glob("*.py"):
        for node in ast.parse(path.read_text()).body:
            if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "revision" for t in node.targets
            ):
                revisions.add(ast.literal_eval(node.value))
    for language in LOCALES.values():
        config = (DOCS / language / "config/environment.md").read_text()
        migrations = (DOCS / language / "deploy/migrations.md").read_text()
        errors.extend(
            f"{language}config/environment: undocumented variable {name}"
            for name in sorted(names)
            if name not in config
        )
        errors.extend(
            f"{language}deploy/migrations: missing revision {rev}"
            for rev in sorted(revisions)
            if rev not in migrations
        )
    print(
        f"Checked {len(names)} platform environment names and {len(revisions)} migration revisions in both languages."
    )
    check_sdk_dependencies(errors)


def check_sdk_dependencies(errors):
    versions = set()
    for module, constant in (("esmc", "ESMC_RUNTIME_VERSION"), ("esm3", "ESM3_RUNTIME_VERSION")):
        tree = ast.parse((ROOT / "pepplatform" / f"{module}.py").read_text())
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(
                isinstance(target, ast.Name) and target.id == constant for target in node.targets
            ):
                versions.add(ast.literal_eval(node.value))
    pins = re.findall(r"^esm==([^\s#]+)\s*$", (ROOT / "requirements-pretrained.txt").read_text(), re.M)
    if len(versions) != 1 or pins != sorted(versions):
        errors.append("Official ESM-C/ESM3 runtime versions and requirements pin disagree")
        return
    version = pins[0]
    headings = {"en": "## Route-Specific Dependencies", "zh": "## 按路线区分依赖"}
    for language, prefix in LOCALES.items():
        path = DOCS / prefix / "install/requirements.md"
        text = path.read_text()
        heading = headings[language]
        section = text.split(heading, 1)[1].split("\n## ", 1)[0] if heading in text else ""
        if not re.search(rf"^\| `esm=={re.escape(version)}` \|", section, re.M):
            errors.append(f"{prefix}install/requirements: missing route-specific esm=={version}")
        if "ESM-C" not in section or "ESM3" not in section or "ESM2" not in section:
            errors.append(f"{prefix}install/requirements: missing SDK route distinctions")
    print("Checked route-specific ESM SDK documentation against source version pins.")


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = []
        self.ids = set()
        self.images = 0
        self.text = []
        self.hidden_text = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag in {"script", "style"}:
            self.hidden_text = tag
        if tag == "br" and self.hidden_text is None:
            self.text.append("\n")
        if tag == "img":
            self.images += 1
        if attrs.get("id"):
            self.ids.add(attrs["id"])
        if tag == "a" and attrs.get("href"):
            self.urls.append(attrs["href"])
        if tag in {"img", "script", "link"}:
            url = attrs.get("src" if tag != "link" else "href")
            if url:
                self.urls.append(url)

    def handle_endtag(self, tag):
        if tag == self.hidden_text:
            self.hidden_text = None
        if self.hidden_text is None and tag in {
            "div", "p", "li", "td", "th", "tr", "pre", "h1", "h2", "h3", "h4", "h5", "h6",
        }:
            self.text.append("\n")

    def handle_data(self, data):
        if self.hidden_text is None:
            self.text.append(data)


def check_dist(dist, errors):
    if not (dist / "index.html").is_file():
        errors.append(f"Build output is missing index.html: {dist}")
        return
    documents = {}
    for path in dist.rglob("*.html"):
        parsed = Links()
        parsed.feed(path.read_text())
        documents[path] = parsed
    base = re.search(r"base:\s*['\"]([^'\"]+)", (DOCS / ".vitepress/config.ts").read_text())[1]
    for source, document in documents.items():
        check_internal_versions("".join(document.text), source.relative_to(dist), errors)
        if document.images:
            errors.append(f"{source.relative_to(dist)}: image in text-only documentation")
        for url in document.urls:
            parts = urlsplit(url)
            if parts.scheme or parts.netloc:
                continue
            path = unquote(parts.path)
            if path.startswith("/"):
                if not path.startswith(base):
                    errors.append(f"{source.relative_to(dist)}: URL outside configured base: {url}")
                    continue
                target = dist / path[len(base) :]
            else:
                target = source if not path else source.parent / path
            target = target.resolve()
            candidates = [target, Path(str(target) + ".html"), target / "index.html"]
            existing = next((p for p in candidates if p.is_file()), None)
            if not existing:
                errors.append(f"{source.relative_to(dist)}: missing built resource {url}")
            elif (
                parts.fragment
                and existing in documents
                and unquote(parts.fragment) not in documents[existing].ids
            ):
                errors.append(f"{source.relative_to(dist)}: missing anchor {url}")
    print(f"Checked links, anchors and resources in {len(documents)} built HTML pages.")


def check_capabilities(actual, errors):
    # Compare the JSON wire representation, where tuples become arrays.
    actual = json.loads(json.dumps(actual))
    # Public excerpts omit objective format versions, but retain every other
    # objective field, list member and ordering constraint in the comparison.
    objectives = actual.get("selection_objectives")
    if isinstance(objectives, list):
        for objective in objectives:
            if isinstance(objective, dict):
                objective.pop("version", None)
    for language in LOCALES.values():
        path = DOCS / language / "api/system.md"
        text = path.read_text().split("<!-- BEGIN CAPABILITIES EXCERPT -->", 1)[1]
        sample = json.loads(re.search(r"```json\s*\n(.*?)```", text, re.S)[1])
        for key, value in sample.items():
            if key not in actual or actual[key] != value:
                errors.append(f"{language}api/system.md: stale capabilities field {key}")
    print("Checked capability excerpts against runtime capabilities.")


def check_runtime(errors):
    # Import pure capability/argument builders only. In particular, importing
    # pepplatform.web.app would initialize the live runtime and is forbidden here.
    sys.path.insert(0, str(ROOT))
    from pepplatform.web.capabilities import build_capabilities, builtin_dataset_specs

    check_capabilities(build_capabilities(), errors)
    # Some formats/paths vary with which optional local data roots exist.
    # The public catalog documents only invariant entry IDs and task types.
    expected_catalog = {spec["id"]: spec["task_type"] for spec in builtin_dataset_specs(ROOT)}
    for prefix in LOCALES.values():
        text = (DOCS / prefix / "datasets/builtin.md").read_text()
        actual_catalog = {}
        for line in text.splitlines():
            cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
            if len(cells) == 2 and cells[0].startswith("`builtin-"):
                actual_catalog[cells[0].strip("`")] = cells[1].strip("`")
        if actual_catalog != expected_catalog:
            errors.append(f"{prefix}datasets/builtin.md: stale catalog IDs or tasks")
    print("Compared documented dataset catalog with source declarations; this does not verify data availability.")
    for script in ("train_sequence_pipeline.py", "train_pair_pipeline.py"):
        path = ROOT / "scripts" / script
        namespace = runpy.run_path(str(path), run_name="docs_parser_check")
        parser = namespace["build_argument_parser"]()
        actual = {
            action.option_strings[0]: action
            for action in parser._actions
            if action.option_strings
            and action.option_strings[0] != "-h"
            and action.help != argparse.SUPPRESS
        }
        documented = {entry["name"]: entry for entry in arguments("scripts/" + script)}
        for name in sorted(actual.keys() - documented.keys()):
            errors.append(f"{script}: extractor misses runtime flag {name}")
        for name in sorted(documented.keys() - actual.keys()):
            errors.append(f"{script}: extractor invents runtime flag {name}")
        for name in actual.keys() & documented.keys():
            action, entry = actual[name], documented[name]
            if entry["default"] != repr(action.default):
                errors.append(f"{script}: default mismatch for {name}")
            if action.choices is not None and entry["choices"] != list(action.choices):
                errors.append(f"{script}: choice mismatch for {name}")
            aliases = set(entry.get("aliases", []))
            if isinstance(action, argparse.BooleanOptionalAction):
                aliases |= {"--no-" + name.removeprefix("--")}
            if aliases != set(action.option_strings[1:]):
                errors.append(f"{script}: alias mismatch for {name}")
        print(
            f"Compared {len(actual)} visible runtime arguments with extracted names, defaults, choices and aliases: {script}"
        )


def main():
    global ROOT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-root", type=Path, default=os.environ.get("PEPPLATFORM_SOURCE_ROOT")
    )
    parser.add_argument("--write-api-index", action="store_true")
    parser.add_argument("--dist", type=Path)
    parser.add_argument(
        "--capabilities-json",
        type=Path,
        help="JSON captured from build_capabilities() in the platform environment",
    )
    parser.add_argument(
        "--runtime",
        action="store_true",
        help="Compare pure capability and parser builders; requires training dependencies, starts no service",
    )
    args = parser.parse_args()
    if args.source_root:
        try:
            ROOT = configure_source_root(args.source_root)
        except ValueError as exc:
            parser.error(str(exc))
    if (args.runtime or args.write_api_index) and ROOT is None:
        parser.error(
            "--runtime and --write-api-index require PEPPLATFORM_SOURCE_ROOT or --source-root"
        )
    arguments.cache_clear()
    routes = source_routes() if ROOT else None
    if args.write_api_index:
        write_indexes(routes)
    errors = []
    check_content(routes, errors)
    if ROOT:
        check_configuration(errors)
        print(f"Compared documentation with {len(routes)} platform API routes.")
    else:
        print("Platform source comparison not requested; checking the standalone site only.")
    if args.capabilities_json:
        check_capabilities(json.loads(args.capabilities_json.read_text()), errors)
    if args.runtime:
        check_runtime(errors)
    if args.dist:
        check_dist(args.dist.resolve(), errors)
    if errors:
        for error in sorted(set(errors)):
            print("ERROR:", error)
        raise SystemExit(1)
    print("Documentation checks passed.")


if __name__ == "__main__":
    main()
